export function findLocationBySlug(slugParam) {
  if (!slugParam) return null;
  const normalized = slugParam.toLowerCase().trim();
  return locationsData.find(
    (loc) =>
      loc.slug === normalized ||
      (loc.aliases && loc.aliases.includes(normalized))
  );
}

